import type { Message, VoiceNote } from '@/data/types';

/** A just-recorded voice note, before it's been uploaded anywhere. */
export type VoiceDraft = {
  id: string;
  from: string;
  to: string;
  at: number;
  /** File URI (native) or blob URL (web) from the recorder. */
  uri: string;
  mimeType: string;
  durationSec: number;
};

/**
 * Where messages live. The screens only talk to MessagesProvider, which talks
 * to one of these — Supabase when it's configured, otherwise this device only.
 */
export type MessagingBackend = {
  /** 'cloud' syncs between phones (and the band); 'local' stays on this device. */
  mode: 'cloud' | 'local';
  /** Every message to or from `me`, and when `me` last read each conversation. */
  load: (me: string) => Promise<{ messages: Message[]; readAt: Record<string, number> }>;
  /** New and changed messages involving `me` (e.g. a transcript arriving). */
  subscribe: (me: string, onMessage: (m: Message) => void) => () => void;
  /** Text and ping messages; the id is generated by the caller. */
  send: (m: Message) => Promise<void>;
  /** Uploads the audio and returns the stored message (transcript to follow). */
  sendVoice: (draft: VoiceDraft) => Promise<Message>;
  markRead: (me: string, other: string, at: number) => Promise<void>;
  /** A URL the audio player can stream, or null if this note has no audio. */
  audioUrl: (note: VoiceNote) => Promise<string | null>;
  registerPushToken: (me: string, token: string) => Promise<void>;
};
